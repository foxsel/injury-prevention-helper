/**
 * 처음 운동 전 통증보다 최근 운동 후 통증이 2점 이상 낮을 때 보여 주는 문구. 효과를 보장하지 않고, 기록된 숫자로 본 "흐름"만 말한다.
 * (PRD: "완치", "100% 예방" 같은 효과 보장 표현 금지)
 */
export function effectMessage(from: number, to: number): string {
  return `처음 기록한 운동 전 통증 ${from}점에서 가장 최근 운동 후 통증 ${to}점으로 ${from - to}점 줄었어요. 이 운동이 효과를 보이는 것으로 보여요. 다만 기록만으로 확정할 수는 없고 사람마다 달라요.`;
}
